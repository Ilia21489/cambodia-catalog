def save(entry, position):
    """Обновляет запись в manual/projects.json и ручные проекты в начале data/projects.json."""
    manual_path = DIR / "projects.json"
    manual = json.loads(manual_path.read_text()) if manual_path.exists() else []
    manual = [p for p in manual if p["slug"] != entry["slug"]]
    manual.insert(min(position, len(manual)), entry)
    manual_path.write_text(json.dumps(manual, ensure_ascii=False, indent=1))
    data_path = DIR.parent / "data" / "projects.json"
    if data_path.exists():
        rest = [p for p in json.loads(data_path.read_text()) if not p["id"].startswith("manual-")]
        data_path.write_text(json.dumps(manual + rest, ensure_ascii=False, indent=1))
    return [p["title"] for p in manual]


