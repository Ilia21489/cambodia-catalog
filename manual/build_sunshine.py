def img(n):
    name = f"{n:03d}.webp"
    w, h = SIZES.get(f"{n:03d}", (1280, 853))
    return {"t": "image", "src": IMG + name, "w": w, "h": h}


def text(html):
    return {"t": "text", "html": html}


def items(*rows):
    return {"t": "list", "items": list(rows)}


def table(*rows):
    return {"t": "table", "header": True, "rows": [list(r) for r in rows]}


def villa(title, ground, upper, render=None, note=""):
    blocks = [img(render)] if render else []
    if note:
        blocks.append(text(note))
    return (title, blocks + [text("<b>Первый этаж</b>"), img(ground), text("<b>Второй этаж</b>"), img(upper)])


